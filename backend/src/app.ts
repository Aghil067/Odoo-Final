import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import cookieParser from 'cookie-parser';
import { rateLimit } from 'express-rate-limit';
import { env } from './config/env.js';
import {db} from './lib/db.js';
import { ApiError, errorHandler, requestContext, success } from './lib/http.js';
import { authRouter, requireTrustedOrigin } from './modules/auth/auth.js';
import { usersRouter } from './modules/auth/users.js';
import { crmRouter } from './modules/crm/routes.js';
import { createSurveyRouter } from './modules/surveys/routes.js';
import { createInstallationRouter } from './modules/installations/routes.js';
import { inventoryRouter } from './modules/inventory/routes.js';
import { createWarrantyRouter } from './modules/warranties/routes.js';
import { createServiceRouter } from './modules/service/routes.js';
import { createFinanceRouter } from './modules/finance/routes.js';
import { analyticsRouter } from './modules/analytics/routes.js';
import { technicianRouter } from './modules/technicians/routes.js';
import { solarRouter } from './modules/solar/routes.js';

export const app = express();
app.disable('x-powered-by');
if (env.TRUST_PROXY_HOPS > 0) app.set('trust proxy', env.TRUST_PROXY_HOPS);
app.use(requestContext, helmet());
app.use(cors({ origin: env.APP_ORIGIN, credentials: true, methods: ['GET', 'POST', 'PATCH', 'PUT', 'OPTIONS'], allowedHeaders: ['Content-Type', 'X-CSRF-Token'], exposedHeaders: ['X-Request-Id'] }));
app.use(rateLimit({ windowMs: 60_000, limit: 200, standardHeaders: 'draft-8', legacyHeaders: false,
  handler: (_req, _res, next) => next(new ApiError(429, 'RATE_LIMITED', 'Too many requests; try again later')),
}));
app.get('/api/health', (_req, res) => success(res, { status: 'ok', module: 'M01' }));
app.get('/api/ready',async(_req,res)=>{try{await db.$queryRaw`SELECT 1`;return success(res,{status:'ready',database:'reachable'});}catch{return res.status(503).json({data:{status:'unavailable',database:'unreachable'}});}});
app.use(requireTrustedOrigin);
app.use((req, _res, next) => {
  const surveyUpload = req.method === 'POST' && (/^\/api\/(surveys|installations)\/[a-f0-9-]{36}\/attachments\/?$/i.test(req.path) || /^\/api\/warranties\/(registrations|claims)\/[a-f0-9-]{36}\/evidence\/?$/i.test(req.path) || /^\/api\/service\/tickets\/[a-f0-9-]{36}\/evidence\/?$/i.test(req.path) || /^\/api\/finance\/(quotations|payments|credit-notes|refunds|expenses|service-charges)\/[a-f0-9-]{36}\/evidence\/?$/i.test(req.path));
  if (['POST', 'PATCH', 'PUT'].includes(req.method) && !surveyUpload && !req.is('application/json')) throw new ApiError(415, 'UNSUPPORTED_MEDIA_TYPE', 'Content-Type must be application/json');
  next();
});
app.use(express.json({ limit: '32kb' }), cookieParser());
app.use('/api/auth', authRouter);
app.use('/api/users', usersRouter);
app.use('/api/surveys', createSurveyRouter());
app.use('/api/solar', solarRouter);
app.use('/api/inventory', inventoryRouter);
app.use('/api/installations', createInstallationRouter());
app.use('/api/technicians', technicianRouter);
app.use('/api/warranties', createWarrantyRouter());
app.use('/api/service', createServiceRouter());
app.use('/api/finance', createFinanceRouter());
app.use('/api/analytics', analyticsRouter);
app.use('/api', crmRouter);
app.use((_req, _res, next) => next(new ApiError(404, 'NOT_FOUND', 'Endpoint not found')));
app.use(errorHandler);
